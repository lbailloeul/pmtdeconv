#!/usr/bin/env python3
"""The shipped dataset cards must stay faithful to the in-code seeds.

``pmtdeconv/data/datasets/*.yaml`` are generated by
``pmtdeconv dataset init <name> --from-seed`` — the migration path from the
Python registry to file-backed cards. They exist so a collaborator configures a
detector by copying YAML instead of editing ``presets/datasets.py``.

The migration is deliberately ADDITIVE: the in-code seeds remain the default
resolution, and these cards are their file-backed twins. That only stays true
if the two cannot drift, which is what this module pins — a seed edited without
regenerating its card fails here.
"""
from __future__ import annotations

import dataclasses
import subprocess
import sys
from pathlib import Path

import pytest

THIS_DIR = Path(__file__).resolve().parent
REPO_ROOT = THIS_DIR.parent
CARD_DIR = REPO_ROOT / "pmtdeconv" / "data" / "datasets"
PYBIN = sys.executable

sys.path.insert(0, str(REPO_ROOT))
from pmtdeconv.presets.datasets import DATASETS, resolve_dataset  # noqa: E402

# `notes` and `meta` are prose/provenance a card may legitimately enrich beyond
# its seed; every field pmtdeconv ACTS on must match exactly.
_PROSE = {"notes", "meta"}


@pytest.mark.parametrize("name", sorted(DATASETS))
def test_every_seed_has_a_card(name):
    assert (CARD_DIR / f"{name}.yaml").exists(), (
        f"no shipped card for dataset {name!r} — regenerate with:\n"
        f"    pmtdeconv dataset init {name} --from-seed "
        f"--out pmtdeconv/data/datasets/{name}.yaml --force")


@pytest.mark.parametrize("name", sorted(DATASETS))
def test_card_round_trips_to_its_seed(name):
    """Resolving the card must reproduce the seed field-for-field."""
    seed = DATASETS[name]
    card = resolve_dataset(str(CARD_DIR / f"{name}.yaml"))
    for f in dataclasses.fields(seed):
        if f.name in _PROSE:
            continue
        assert getattr(card, f.name) == getattr(seed, f.name), (
            f"{name}.{f.name} drifted: card={getattr(card, f.name)!r} "
            f"seed={getattr(seed, f.name)!r} — regenerate the card")


@pytest.mark.parametrize("name", sorted(DATASETS))
def test_shipped_card_is_machine_independent(name):
    """A shipped card must not hard-code the author's filesystem.

    Data paths use ``${PMTDECONV_DATA_ROOT}`` (resolved per machine); the
    bundled SPE templates are referenced relative to the card. An absolute
    path here would resolve to nothing on a collaborator's checkout.
    """
    text = (CARD_DIR / f"{name}.yaml").read_text()
    offenders = [ln.strip() for ln in text.splitlines()
                 if ("/Users/" in ln or "/home/" in ln) and not ln.startswith("#")]
    assert not offenders, f"absolute path(s) in {name}.yaml: {offenders}"


@pytest.mark.parametrize("name", sorted(DATASETS))
def test_shipped_card_lints_clean(name):
    res = subprocess.run(
        [PYBIN, "-m", "pmtdeconv", "dataset", "lint",
         str(CARD_DIR / f"{name}.yaml")],
        cwd=REPO_ROOT, capture_output=True, text=True)
    assert res.returncode == 0, f"{name}.yaml failed lint:\n{res.stdout}{res.stderr}"


def test_card_is_recorded_as_a_manifest_input(tmp_path):
    """A run driven by a card names that card in the manifest inputs, so
    `--hash-inputs` can fingerprint the configuration, not just the data."""
    import json
    from types import SimpleNamespace
    from pmtdeconv.io.manifest import write_manifest
    from pmtdeconv.presets import resolve_settings

    card = CARD_DIR / "na22.yaml"
    settings, _ = resolve_settings(SimpleNamespace(dataset=str(card)),
                                   require_data_root=False)
    assert settings.dataset_card_path is not None

    out = tmp_path / "manifest.json"
    write_manifest(subcommand="area", settings=settings, provenance={},
                   inputs=[], outputs=[], out_path=out)
    manifest = json.loads(out.read_text())
    roles = {i["role"] for i in manifest["inputs"]}
    assert "dataset_card" in roles


def test_shipped_card_is_what_a_name_resolves_to(tmp_path, monkeypatch):
    """`--dataset na22` must resolve the SHIPPED card, not skip to the seed.

    Before 2026-09-21 name lookup went data-root card -> in-code seed, so the
    shipped `pmtdeconv/data/datasets/*.yaml` were inert: editing one changed
    nothing. Swap in a modified card and the resolved setting must follow it,
    still labelled [dataset] (it is the default, not a user override)."""
    import yaml
    from pmtdeconv.presets import datasets as ds_mod
    card = yaml.safe_load((CARD_DIR / "na22.yaml").read_text())
    card["cosine_cutoff_mhz"] = 123.0
    edited = tmp_path / "na22.yaml"
    edited.write_text(yaml.safe_dump(card))
    monkeypatch.setattr(ds_mod, "_shipped_card_path",
                        lambda name: edited if name == "na22" else None)
    monkeypatch.setattr(ds_mod, "_registry_card_path", lambda name: None)

    preset, source, _ = ds_mod.resolve_dataset_with_source("na22")
    assert preset.cosine_cutoff_mhz == 123.0
    assert source == "dataset"


def test_user_registry_card_still_beats_the_shipped_card(tmp_path, monkeypatch):
    """Order is data-root card -> shipped card -> seed: a collaborator's card
    on the shared share must override the default, and be labelled [card]."""
    import yaml
    calib = tmp_path / "calibrations" / "datasets"
    calib.mkdir(parents=True)
    card = yaml.safe_load((CARD_DIR / "na22.yaml").read_text())
    card["cosine_cutoff_mhz"] = 77.0
    (calib / "na22.yaml").write_text(yaml.safe_dump(card))
    monkeypatch.setenv("PMTDECONV_DATA_ROOT", str(tmp_path))
    from pmtdeconv.presets.datasets import resolve_dataset_with_source
    preset, source, _ = resolve_dataset_with_source("na22")
    assert preset.cosine_cutoff_mhz == 77.0
    assert source == "card"
